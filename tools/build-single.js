#!/usr/bin/env node
// Compiles the game into one self-contained file, snake-plus.html, from index.html and everything it loads.
//   node tools/build-single.js          rebuild
//   node tools/build-single.js --check  fail if snake-plus.html is out of date
// The game itself still has no build step: index.html runs as it is.
'use strict';
const fs = require('fs'), path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'snake-plus.html');
const read = f => fs.readFileSync(path.join(ROOT, f), 'utf8');
const dataUri = f => 'data:image/png;base64,' + fs.readFileSync(path.join(ROOT, f)).toString('base64');
function need(s, re, what) { if (!re.test(s)) throw new Error('build-single: could not find ' + what + ' in index.html'); }

function build() {
  let h = read('index.html');
  // Functions as replacers: the code contains $ patterns that would otherwise be treated specially.
  need(h, /<link rel="stylesheet" href="style\.css">/, 'the stylesheet');
  h = h.replace('<link rel="stylesheet" href="style.css">', () => '<style>\n' + read('style.css').replace(/<\/style/gi, '<\\/style') + '</style>');

  // Hosted anywhere or opened as a file, this copy always talks to the real sync server.
  const live = /const LIVE = '([^']+)'/.exec(read('js/sync.js'));
  if (!live) throw new Error('build-single: could not find the sync server address in js/sync.js');
  need(h, /<script src="js\/[\w.-]+\.js"><\/script>/, 'the scripts');
  let first = true;
  h = h.replace(/<script src="(js\/[\w.-]+\.js)"><\/script>/g, (m, f) => {
    const code = read(f).replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');
    const pre = first ? '<script>window.SNAKE_SYNC_API = ' + JSON.stringify(live[1]) + ';</script>\n' : '';
    first = false;
    return pre + '<script>\n' + code + '</script>';
  });

  need(h, /href="icons\//, 'the icons');
  h = h.replace(/href="(icons\/[\w.-]+\.png)"/g, (m, f) => 'href="' + dataUri(f) + '"');

  // The manifest and offline worker are separate files, so they can't come along.
  const pwa = /<script>\s*\/\/ Offline support[\s\S]*?<\/script>\n?/;
  need(h, pwa, 'the offline/install script');
  h = h.replace(pwa, '');

  h = h.replace(/^<!doctype html>\n/i, m => m + '<!-- Generated by tools/build-single.js. Do not edit: change the source files instead. -->\n');

  // Nothing local may be left behind, or the file would break once moved.
  const left = /(?:src|href)="(?!https:|data:|#)[^"]+"|sw\.js|manifest\.webmanifest/.exec(h.replace(/<script>[\s\S]*?<\/script>|<style>[\s\S]*?<\/style>/g, ''));
  if (left) throw new Error('build-single: still points at a local file: ' + left[0]);
  return h;
}

const html = build();
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== html) { console.error('snake-plus.html is out of date: run node tools/build-single.js'); process.exit(1); }
  console.log('snake-plus.html is up to date');
} else {
  fs.writeFileSync(OUT, html);
  console.log('Built snake-plus.html (' + Math.round(Buffer.byteLength(html) / 1024) + ' KB)');
}
